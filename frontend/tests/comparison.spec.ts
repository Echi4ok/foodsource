import { expect, test } from '@playwright/test'

test('records an answer without exposing the comparison behind the editor', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2030-02-01T12:00:00Z'))
  await page.goto('/')
  const catalog = await page.request.get('/api/catalog')
  expect(catalog.ok()).toBe(true)
  const { updated_at: snapshotDate } = await catalog.json()
  await expect(page.locator('.catalog-date time')).toHaveAttribute('datetime', snapshotDate)
  const checkboxes = page.getByRole('checkbox')
  for (let index = 0; index < 3; index++) await checkboxes.nth(index).check()
  await page.getByRole('button', { name: 'Сравнить 3/3' }).click()

  const comparison = page.getByRole('dialog', { name: 'Сравнение поставщиков' })
  const scroller = comparison.getByRole('region', { name: 'Таблица условий поставщиков' })
  const table = page.locator('.comparison-table')
  const record = comparison.getByRole('button', { name: /^Записать ответ/ }).last()
  await expect(comparison.getByRole('columnheader')).toHaveCount(4)
  await record.scrollIntoViewIfNeeded()
  const scrollLeft = await scroller.evaluate((element) => element.scrollLeft)
  expect(scrollLeft).toBeGreaterThan(0)
  const geometry = await comparison.boundingBox()
  await record.click()

  const editor = page.getByRole('dialog', { name: 'Запись об ответе' })
  await expect(editor.getByRole('heading')).toBeFocused()
  await expect(table).toBeHidden()
  expect(await editor.boundingBox()).toEqual(geometry)

  const unit = editor.getByRole('combobox', { name: /^За единицу/ })
  await unit.click()
  await expect(editor.getByRole('option', { name: 'кг', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(unit).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('Escape')
  await expect(record).toBeFocused()
  expect(await scroller.evaluate((element) => element.scrollLeft)).toBe(scrollLeft)

  await record.click()
  await editor.getByLabel('Товар', { exact: true }).fill('Товар для пробы')
  await editor.getByRole('button', { name: 'Сохранить запись' }).click()
  await expect(comparison.getByText('Товар для пробы', { exact: true })).toBeVisible()
  await expect(comparison.getByRole('button', { name: /^Изменить запись/ })).toBeFocused()
  await expect(comparison.getByRole('columnheader')).toHaveCount(4)
  expect(await scroller.evaluate((element) => element.scrollLeft)).toBe(scrollLeft)
})
